create table if not exists game_state (
    game_id bigint generated by default as identity primary key,
    current_turn varchar(20) not null
);

create table if not exists game_piece (
    game_id bigint not null,
    row_position int not null,
    column_position int not null,
    piece_type varchar(30) not null,
    camp varchar(20) not null,
    primary key (game_id, row_position, column_position),
    foreign key (game_id) references game_state(game_id)
);
